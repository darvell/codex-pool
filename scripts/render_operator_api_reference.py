#!/usr/bin/env python3
"""Render the checked-in Operator API route reference from deployed OpenAPI."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs/openapi/operator-v1.openapi.json"
OUTPUT = ROOT / "docs/operator-api-reference.md"
METHODS = ("get", "post", "put", "patch", "delete", "head", "options")


def render() -> str:
    spec = json.loads(SPEC.read_text())
    groups: dict[str, list[str]] = {"operator.read": [], "operator.write": []}
    for path, item in spec["paths"].items():
        for method in METHODS:
            operation = item.get(method)
            if not operation:
                continue
            capability = operation["x-operator-capability"]
            groups[capability].append(
                f"| `{method.upper()}` | `{path}` | {operation['summary']} |"
            )
    lines = [
        "<!-- Generated by scripts/render_operator_api_reference.py; do not edit. -->",
        "# Operator API route reference",
        "",
        "The running pool serves the complete, version-matched contract at `GET /api/operator/v1/openapi.json`. All calls use `Authorization: Bearer poolop_…`.",
        "",
    ]
    for capability, title in (("operator.read", "Read-only and read + write"), ("operator.write", "Read + write only")):
        lines += [f"## {title}", "", "| Method | Path | Operation |", "|---|---|---|", *sorted(groups[capability]), ""]
    return "\n".join(lines)


if __name__ == "__main__":
    OUTPUT.write_text(render())
